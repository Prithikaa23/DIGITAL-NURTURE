public class typecasting {
    public static void main(String[] args) {

        double num1 = 10.75;
        int num2 = (int) num1;

        System.out.println("Double: " + num1);
        System.out.println(" Int: " + num2);

        int num3 = 20;
        double num4 = (double) num3;

        System.out.println("Int : " + num3);
        System.out.println("Double: " + num4);
    }
}
